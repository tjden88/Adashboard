namespace Adashboard.Client.Services;

/// <summary>
/// Декларативный REST-клиент к Adashboard.Server, построенный библиотекой Refit.
/// </summary>
/// <remarks>
/// <para>
/// Сам интерфейс не пишется руками: он генерируется на сборке клиента по OpenAPI-документу
/// сервера. Всё, что относится к конвейеру генерации, живёт в трёх местах:
/// <list type="number">
/// <item><description>
/// <c>Adashboard.Server</c> — контроллеры описывают API; сборка сервера генерирует
/// OpenAPI-документ и кладёт его копию в <c>openapi/Adashboard.Server.json</c> в корне решения.
/// </description></item>
/// <item><description>
/// <c>Adashboard.Client/dashboard-api.refitter</c> — настройки генератора Refitter: какая
/// спецификация берётся, как называются интерфейс и методы, какие типы ответов переопределяются.
/// </description></item>
/// <item><description>
/// <c>Adashboard.Client/Generated/IDashboardApi.g.cs</c> — результат генерации; файл создаётся
/// на каждой сборке клиента, в репозиторий не попадает и править его бессмысленно.
/// </description></item>
/// </list>
/// Поэтому «изменился API — изменился клиент» работает так: правки в контроллерах сервера
/// (маршрут, параметры, типы) попадают в спецификацию, а из неё Refitter пересобирает методы.
/// Руками в клиенте ничего синхронизировать не нужно.
/// </para>
/// <para>
/// Refit — это библиотека, которая по обычному C#-интерфейсу генерирует реализацию HTTP-клиента.
/// Достаточно описать методы и повесить атрибуты, а код запросов (сборка URL, сериализация тела,
/// десериализация ответа) Refit сгенерирует сам во время компиляции. Поэтому в клиенте нет ни одного
/// ручного вызова <c>HttpClient</c> — только описание контракта.
/// </para>
/// <para>
/// Базовый адрес API задаётся один раз при регистрации клиента в <c>Program.cs</c> через
/// <c>AddRefitGeneratedClient&lt;IDashboardApi&gt;()</c>. Относительные пути из атрибутов
/// (например, <c>/api/layout</c>) Refit приклеивает к этому базовому адресу.
/// </para>
/// <para>
/// Атрибуты в сгенерированных методах:
/// <list type="bullet">
/// <item><description><c>[Get]</c> — HTTP GET, читает данные. Ответ десериализуется в указанный тип.</description></item>
/// <item><description><c>[Post]</c> — HTTP POST, создаёт ресурс; сервер возвращает созданную модель с назначенным Id.</description></item>
/// <item><description><c>[Put]</c> — HTTP PUT, изменяет существующий ресурс (обычно ответ 204 без тела).</description></item>
/// <item><description><c>[Delete]</c> — HTTP DELETE, удаляет ресурс.</description></item>
/// <item><description><c>[Body]</c> — помечает параметр как тело запроса (по умолчанию JSON).</description></item>
/// <item><description><c>[Multipart]</c> — отправка файла как <c>multipart/form-data</c>; имя поля формы берётся из имени параметра (<c>file</c>).</description></item>
/// <item><description><c>[Query]</c> — подставляет значение как параметр строки запроса (<c>?url=...</c>).</description></item>
/// </list>
/// </para>
/// <para>
/// Фигурные скобки в пути (<c>{id}</c>) — это подстановка значений параметров метода в URL.
/// </para>
/// <para>
/// Важно про модели: API разделяет чтение и запись. Агрегат для отображения отдаёт read-модель
/// <c>DashboardLayoutReadModel</c> (плоские списки категорий и карточек), а команды создания
/// и изменения принимают плоские контрактные модели <c>DashboardCategory</c> и <c>DashboardCard</c>.
/// Все эти модели лежат в <c>Adashboard.Domain</c> и переиспользуются обеими сторонами, поэтому
/// генератор клиента не создаёт собственных копий контрактов.
/// </para>
/// <para>
/// Этот файл — рукописная (<c>partial</c>) половина интерфейса. Здесь остаётся только то, чего нет
/// в спецификации API: сейчас это клиентский лимит на размер изображения.
/// </para>
/// </remarks>
public partial interface IDashboardApi
{
    /// <summary>
    /// Максимальный размер принимаемого изображения-иконки в байтах.
    /// </summary>
    /// <remarks>
    /// То же ограничение действует на стороне API (проверка перед сохранением файла),
    /// поэтому клиент отсекает слишком большие изображения ещё до отправки.
    /// </remarks>
    const long MaxImageBytes = 2 * 1024 * 1024;
}
