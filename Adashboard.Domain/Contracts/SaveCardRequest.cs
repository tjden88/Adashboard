namespace Adashboard.Domain.Contracts;

/// <summary>
/// Запрос создания и изменения карточки: сама карточка и необязательное новое изображение-иконка.
/// Изображение идёт вместе с карточкой, потому что файл сохраняется для уже существующей карточки:
/// так создание и замена иконки выполняются одним запросом, без частично созданных карточек.
/// </summary>
public sealed class SaveCardRequest
{
    /// <summary>
    /// Карточка: при создании идентификатор не задан, при изменении — задан.
    /// </summary>
    public DashboardCard Card { get; set; } = new();

    /// <summary>
    /// Содержимое нового изображения-иконки или <c>null</c>, если изображение не меняется.
    /// </summary>
    public byte[]? ImageContent { get; set; }
}
